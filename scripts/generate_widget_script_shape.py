"""Generate literal admission data from the recorded, audited widget graph.

This never accesses the game. Operand offsets are the reviewed inventory, not
inferred pointer-like bytes. Any new graph needs a new review of every operand.
"""
import json
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[1]
def main():
    rows=json.loads((ROOT/'evidence/widget-track-profile-current.json').read_text())
    code=bytearray.fromhex(next(r for r in rows if r['event']=='blueprint_script')['hex'])
    assert len(code)==690
    fields={int(r['field_address'],16):r for r in rows if r['event']=='property_metadata'}
    # Exact reviewed FField operand positions.
    field_offsets=[2,12,34,59,93,104,140,164,182,200,211,225,243,270,288,299,
                   310,345,357,366,377,399,424,458,474,524,551,569,580,590,612,632,644,653,665,674]
    unique=[];bindings=[]
    owner_ids={'ExecuteUbergraph_BP_WidgetSequencerTrackInstance':0,
               'BP_WidgetSequencerTrackInstance_C':1,'BP_WidgetSequencerSection_C':2}
    for offset in field_offsets:
        field=fields[struct.unpack_from('<Q',code,offset)[0]]
        if field not in unique:unique.append(field)
        bindings.append((offset,unique.index(field)))
    # IDs beyond the field table are resolved and checked by the native profile.
    extra=[(22,0),(173,1),(252,2),(261,3),(387,0),(495,4),(533,2),(542,3),(600,5),(621,6)]
    names=[(43,'GetCinematicsSystem'),(80,'UnregisterSpawnedWidget'),(125,'RemoveFromParent'),
           (331,'BPI_SetWidgetParameters'),(408,'GetCinematicsSystem'),(445,'RegisterSpawnedWidget')]
    bindings += [(offset,len(unique)+index) for offset,index in extra]
    bindings += [(offset,len(unique)+7+index) for index,(offset,_) in enumerate(names)]
    bindings.sort()
    used=set()
    for offset,_ in bindings:
        assert not used.intersection(range(offset,offset+8))
        used.update(range(offset,offset+8));code[offset:offset+8]=b'\0'*8
    out=['// Generated by scripts/generate_widget_script_shape.py; reviewed 690-byte graph.',
         '#pragma once','namespace e33_cinematic {',
         'struct WidgetScriptField { uint32_t owner; const char* name; uint32_t offset,width; uint64_t vtable,flags; uint32_t name_number; };',
         'inline constexpr WidgetScriptField widget_fields[]={']
    for f in unique:
        # Require observed components, never infer a numeric suffix from text.
        out.append('    {%d,"%s",%d,%d,%s,%sULL,%d},'%(owner_ids[f['owner']],f['name_base'],f['offset'],f['element_size'],f['vtable_rva'],f['flags'],f['name_number']))
    out+=['};','inline constexpr uint8_t widget_graph_bytes[]={']
    for i in range(0,len(code),16):out.append('    '+','.join(f'0x{x:02x}' for x in code[i:i+16])+',')
    out+=['};','inline constexpr uint32_t widget_binding_offsets[]={'+','.join(str(x[0]) for x in bindings)+'};',
          'inline constexpr uint32_t widget_binding_values[]={'+','.join(str(x[1]) for x in bindings)+'};',
          'inline constexpr uint32_t widget_name_offsets[]={'+','.join(str(x[0]) for x in names)+'};',
          'inline constexpr const char* widget_names[]={'+','.join(json.dumps(x[1]) for x in names)+'};','}']
    (ROOT/'native/cinematic_track_shape.h').write_text('\n'.join(out)+'\n')
    callbacks=[json.loads(line) for line in (ROOT/'evidence/widget-component-callbacks-current.jsonl').read_text(encoding='utf-8-sig').splitlines()]
    scripts={row['index']:bytes.fromhex(row['hex']) for row in callbacks if row['event']=='blueprint_script'}
    callback_out=['// Generated reviewed widget registration and null-control branch shapes.',
                  '#pragma once','namespace e33_cinematic {']
    for name,index,size,offsets in (
        ('register',79367,85,[1,10,20,32,41,50,59,69]),
        ('unregister',79382,77,[2,12,24,33,42,51,61]),
        ('controls_null_prefix',79383,43,[2,11,20,35])):
        raw=bytearray(scripts[index][:size]);assert len(raw)==size
        for offset in offsets:raw[offset:offset+8]=b'\0'*8
        callback_out+=['inline constexpr uint8_t widget_'+name+'_bytes[]={'+','.join(f'0x{x:02x}' for x in raw)+'};',
                       'inline constexpr uint32_t widget_'+name+'_offsets[]={'+','.join(map(str,offsets))+'};']
    assert scripts[79383][282:]==bytes([4,11,83])
    callback_out+=['}']
    (ROOT/'native/cinematic_callback_shapes.h').write_text('\n'.join(callback_out)+'\n')
    print(json.dumps(dict(bytes=len(code),fields=len(unique),bindings=len(bindings),name_calls=len(names))))

if __name__=='__main__':main()
